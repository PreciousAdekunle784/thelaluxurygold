#!/usr/bin/env node
/**
 * Media pipeline.
 *
 *   npm run media                     → rebuild src/lib/data/media.generated.ts from public/images
 *   npm run media -- --import <dir>   → convert JPG/PNG files in <dir> to WebP under public/images first
 *
 * Keys are paths relative to public/images/laluxurygold without extension, e.g. "products/aurelia-band-1".
 */
import { readdir, mkdir, writeFile, stat } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const imagesDir = path.join(root, "public", "images", "laluxurygold");
const out = path.join(root, "src", "lib", "data", "media.generated.ts");

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
  const files = await Promise.all(entries.map((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)])));
  return files.flat();
}

const args = process.argv.slice(2);
const importIdx = args.indexOf("--import");
if (importIdx !== -1) {
  const src = path.resolve(args[importIdx + 1]);
  for (const f of await walk(src)) {
    if (!/\.(jpe?g|png)$/i.test(f)) continue;
    const rel = path.relative(src, f).replace(/\.(jpe?g|png)$/i, ".webp");
    const dest = path.join(imagesDir, rel);
    await mkdir(path.dirname(dest), { recursive: true });
    await sharp(f).webp({ quality: 82, effort: 5 }).toFile(dest);
    console.log("imported", rel);
  }
}

const manifest = {};
for (const f of (await walk(imagesDir)).sort()) {
  if (!/\.(webp|jpe?g|png|avif)$/i.test(f)) continue;
  const key = path.relative(imagesDir, f).replace(/\\/g, "/").replace(/\.[a-z]+$/i, "");
  const meta = await sharp(f).metadata();
  const blur = await sharp(f).resize(16, Math.max(1, Math.round((16 * meta.height) / meta.width))).webp({ quality: 40 }).toBuffer();
  manifest[key] = [meta.width, meta.height, `data:image/webp;base64,${blur.toString("base64")}`];
}

const body = `// Generated by scripts/media.mjs — do not edit by hand.\n// [width, height, blurDataURL]\nexport const mediaManifest: Record<string, [number, number, string]> = ${JSON.stringify(manifest, null, 2)};\n`;
await writeFile(out, body);
const size = (await stat(out)).size;
console.log(`media manifest: ${Object.keys(manifest).length} assets (${(size / 1024).toFixed(1)} KB)`);
